/* Task 1: List 3 real-world scenarios where your favorite apps (like Zomato, WhatsApp, 
or Spotify) use local storage to improve user experience when there is no internet connection, 
and explain in 1-2 lines how local storage helps in each case.*/

//--------Answer------
/*1. WhatsApp: reading old chats offline
WhatsApp keeps your messages and media in a local database on the phone. You can open any 
past conversation without internet, and messages you send while offline wait on the device 
and go out when the connection returns.*/

/*
2. Spotify: playing downloaded songs and playlists
Premium users download tracks to the device, so music plays on a flight or in an 
area with no signal. The app also saves your library and playlist details locally, so those 
screens still load.
*/

/*
3. Zomato: viewing past orders and saved addresses
Order history, saved addresses and recently viewed restaurants 
are cached on the device. Without internet you can still see your previous orders and reorder 
details instead of getting a blank error screen.
*/
